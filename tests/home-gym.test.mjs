import ts from 'typescript';
import {readFileSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
function compile(file){const code=ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;const module={exports:{}};new Function('require','module','exports',code)(require,module,module.exports);return module.exports;}
const fullCatalog=JSON.parse(readFileSync('data/catalog.json','utf8'));
const laterIds=new Set(JSON.parse(readFileSync('research/high-ticket-expansion-2026-10-17.json','utf8')).products.map(p=>p.productId));
const products=fullCatalog.filter(p=>!laterIds.has(p.id));
const record=JSON.parse(readFileSync('research/home-gym-expansion-2026-10-17.json','utf8'));
const ids=new Set(record.products.map(p=>p.productId));
const added=products.filter(p=>ids.has(p.id));
const {productSchema}=compile('lib/validation.ts');
const {parseBrowse,filterProducts,browseUrl,facetValues,recoveryFacetProducts,selectRecoveryType}=compile('lib/browse.ts');
const {canCompare}=compile('lib/catalog.ts');
let checks=0;const check=(ok,label)=>{assert.ok(ok,label);checks++;};
const find=(query={})=>filterProducts(products,parseBrowse('recovery',{deviceType:'home-gym',...query}));
check(added.length===10&&products.length===118,'10 new products, 118 total');
for(const [type,count] of Object.entries({'adjustable-dumbbells':3,'power-rack':2,bench:2,barbell:1,'weight-plates':1,'functional-trainer':1}))check(find({equipmentType:type}).length===count,type+' coverage');
for(const p of added){
 check(productSchema.safeParse(p).success,p.id+' schema');
 check(existsSync('public'+p.image),p.id+' real local product image');
 check(p.price>0&&p.checked==='2026-10-17'&&p.source.startsWith('https://'),p.id+' dated price source');
 check(p.affiliate===false&&!('score' in p)&&!('trustScore' in p),p.id+' no invented tracking or evidence');
 check(p.filters.indoor===true&&p.facets.placement.includes('indoor'),p.id+' indoor use');
 check(p.attributes['Weight range']||p.attributes['Weight capacity'],p.id+' weight information');
 for(const key of ['Dimensions','Construction','Warranty','Included','Price basis'])check(Boolean(p.attributes[key]),p.id+' '+key);
 check(Object.values(p.attributes).some(v=>v.startsWith('https://')),p.id+' linked evidence');
 check(find().some(x=>x.id===p.id),p.id+' discoverable');
 check(facetValues(p,'priceBand').length===1,p.id+' price band');
}
check(find({equipmentType:'bench,power-rack'}).length===4,'OR within equipment type');
check(find({equipmentType:'adjustable-dumbbells',adjustment:'rotating-handle',priceBand:'500-999'}).map(p=>p.id).join()==='smrtft-nuobell-80','type, mechanism and budget combine');
check(find({equipmentType:'bench',benchPosition:'incline'}).length===1,'incline only excludes the flat bench');
check(find({equipmentType:'bench',benchPosition:'flat'}).length===2,'flat position includes both bench types');
check(find({equipmentType:'power-rack',setup:'wall-mounted'}).length===1,'folding rack installation is findable');
check(find({equipmentType:'adjustable-dumbbells',min:'800',sort:'price-asc'}).length===2,'minimum budget filters dumbbell pairs');
check(find({temperature:'below-40f'}).length===0,'gym equipment never inherits recovery temperature claims');
check(find({equipmentType:'barbell',weightRange:'5–90 lb each'}).length===0,'weight range does not match unspecified values');
check(find({equipmentType:'adjustable-dumbbells',warranty:'5-year'}).every(p=>p.id!=='powerblock-elite-usa-90'),'shorter pin warranty is not presented as five-year minimum');
const sample=added[0];
for(const [price,band] of [[249.99,'under-250'],[250,'250-499'],[499.99,'250-499'],[500,'500-999'],[1000,'1000-2499'],[2499.99,'1000-2499'],[2500,'2500-plus']])check(facetValues({...sample,price},'priceBand')[0]===band,'price boundary '+price);
check(facetValues({...sample,price:NaN},'priceBand').length===0,'unknown price never qualifies');
check(facetValues({...sample,category:'supplements'},'priceBand').length===0,'equipment budget bands stay in recovery');
const state=parseBrowse('recovery',{deviceType:'home-gym',equipmentType:'adjustable-dumbbells',weightRange:'5–90 lb each',construction:'steel-plates',adjustment:'magnetic-pin',priceBand:'500-999',placement:'indoor',sort:'price-desc'});
assert.deepEqual(parseBrowse('recovery',Object.fromEntries(new URL(browseUrl(state),'https://example.test').searchParams)),state);checks++;
check(recoveryFacetProducts(products,state,'weightRange').every(p=>p.type==='adjustable-dumbbells'),'weight options are scoped to dumbbells');
check(recoveryFacetProducts(products,state,'equipmentType').length===10,'equipment siblings remain discoverable');
const switched={...state,...selectRecoveryType(state,'sauna')};
check(!switched.selected.equipmentType&&!switched.selected.weightRange&&filterProducts(products,switched).length===3,'collection switching clears incompatible gym filters');
const dumbbells=find({equipmentType:'adjustable-dumbbells'}),benches=find({equipmentType:'bench'});
check(canCompare([dumbbells[0]],dumbbells[1]),'dumbbell comparison works');
check(canCompare([benches[0]],benches[1]),'flat and adjustable benches compare together');
check(!canCompare([benches[0]],dumbbells[0]),'bench and dumbbell specs are not falsely compared');
console.log(`${checks} home-gym catalog and filter checks passed.`);
